def strip_obj(html, qid):
    token = '{id:"%s"' % qid
    i = html.find(token)
    if i < 0:
        print("missing delete", qid)
        return html
    j = html.find("},", i)
    if j < 0:
        return html
    return html[:i] + html[j+2:]
