def strip_obj(html, qid):
    token = '{id:"%s"' % qid
    i = html.find(token)
    if i < 0:
        print("missing delete", qid)
        return html
    j = html.find("},", i)
    if j < 0:
        return html
    return html[:i] + html[j+2:]
def replace_obj(html, qid, new):
    token = '{id:"%s"' % qid
    i = html.find(token)
    if i < 0:
        print("missing replace", qid)
        return html
    body = new.rstrip().rstrip(",").rstrip("}") + "}"
    j = html.find("},", i)
    if j < 0:
        j = html.find("}", i)
        if j < 0:
            return html
        return html[:i] + body + "," + html[j+1:]
    return html[:i] + body + "," + html[j+2:]
